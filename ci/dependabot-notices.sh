#!/usr/bin/env bash
# SPDX-License-Identifier: AGPL-3.0-or-later
# Pushes a regenerated ui/THIRD-PARTY-NOTICES.txt to a Dependabot npm PR's branch as one bot commit
# (.github/workflows/dependabot-notices.yml). The file is data produced by the PR's own build
# (dependabot-notices-build.yml); this script never runs anything from the PR, only git and cp.
#
# Pushes only when ALL hold, otherwise prints why and exits 0:
#   - the branch is a `dependabot/npm_and_yarn/ui/` branch with one open PR into develop, authored by
#     dependabot[bot], from this repository;
#   - the branch tip is still <head sha>, the commit the build ran on (a newer Dependabot push means a
#     newer build run will follow);
#   - the file starts with the notices heading and is at most 2 MiB;
#   - it differs from the branch's ui/THIRD-PARTY-NOTICES.txt.
# The commit touches that one path, and the push is a fast-forward. A push with the workflow token starts no checks,
# so afterwards the four required workflows are dispatched on the branch (checks attach to the head commit by name),
# and auto-merge is armed again for the new head when the PR already had it (its `--match-head-commit` names the old
# head); it never arms by itself.
# Usage: ci/dependabot-notices.sh <branch> <head sha> <file>   Needs GH_TOKEN, GITHUB_REPOSITORY.
# NOTICES_REMOTE overrides the clone URL. Self-test: ci/dependabot-notices-test.sh.
set -euo pipefail

branch=${1:?usage: dependabot-notices.sh <branch> <head sha> <file>}
expect=${2:?}
file=$(cd "$(dirname -- "${3:?}")" && pwd)/$(basename -- "$3")
repo=${GITHUB_REPOSITORY:?GITHUB_REPOSITORY not set}
remote=${NOTICES_REMOTE:-https://github.com/$repo.git}
path=ui/THIRD-PARTY-NOTICES.txt
heading="Third-party software shipped in "
workflows=(ci.yml windows.yml vm-linux.yml vm-windows.yml)

skip() { echo "dependabot-notices: $branch: nothing pushed: $*"; exit 0; }

case $branch in
dependabot/npm_and_yarn/ui/*) ;;
*) skip "not a ui npm branch" ;;
esac

prs=$(gh api "repos/$repo/pulls?state=open&base=develop&head=${repo%%/*}:$branch")
[ "$(jq length <<<"$prs")" = 1 ] || skip "expected one open PR into develop"
pr=$(jq '.[0]' <<<"$prs")
jq -e --arg repo "$repo" '.user.login == "dependabot[bot]" and .head.repo.full_name == $repo and (.draft | not)' <<<"$pr" >/dev/null ||
    skip "PR is not an own-repo Dependabot PR"
number=$(jq -r .number <<<"$pr")
[ "$(jq -r .head.sha <<<"$pr")" = "$expect" ] || skip "branch moved past $expect"

[ -f "$file" ] && [ ! -L "$file" ] || skip "$file is not a regular file"
[ "$(wc -c <"$file")" -le 2097152 ] || skip "$file is over 2 MiB"
case $(head -n 1 "$file") in "$heading"*) ;; *) skip "$file lacks the notices heading" ;; esac

tmp=$(mktemp -d "${TMPDIR:-/tmp}/dependabot-notices.XXXXXX")
trap 'rm -rf "$tmp"' EXIT
auth=()
if [ -n "${GH_TOKEN:-}" ]; then
    auth=(-c "http.extraheader=AUTHORIZATION: basic $(printf 'x-access-token:%s' "$GH_TOKEN" | base64 -w0)")
fi
git "${auth[@]}" clone --quiet --depth 1 --no-tags --branch "$branch" "$remote" "$tmp/repo"
cd "$tmp/repo"
[ "$(git rev-parse HEAD)" = "$expect" ] || skip "branch tip is not $expect"
if cmp -s "$file" "$path"; then skip "$path is already current"; fi

cp "$file" "$path"
git add -- "$path"
[ "$(git diff --cached --name-only)" = "$path" ] || skip "more than $path changed"
git -c user.name='github-actions[bot]' -c user.email='41898282+github-actions[bot]@users.noreply.github.com' \
    commit --quiet -m "chore(ui): regenerate third-party notices for the npm bump" \
    -m "Regenerated by the workflow from the build of $expect (npm run licences)."
git "${auth[@]}" push --quiet origin "HEAD:refs/heads/$branch"
new=$(git rev-parse HEAD)
echo "dependabot-notices: PR #$number: pushed $new ($(git diff --shortstat "$expect" "$new"))"

for wf in "${workflows[@]}"; do
    gh workflow run "$wf" -R "$repo" --ref "$branch" ||
        { echo "dependabot-notices: dispatching $wf failed; run: gh workflow run $wf -R $repo --ref $branch" >&2; exit 1; }
done
if jq -e '.auto_merge != null' <<<"$pr" >/dev/null; then
    gh pr merge "$number" -R "$repo" --auto --squash --match-head-commit "$new"
fi
